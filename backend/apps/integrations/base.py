from abc import ABC, abstractmethod


class EmailIntegration(ABC):
    enabled = False

    @abstractmethod
    def connect(self, consent): ...
    @abstractmethod
    def disconnect(self): ...
    @abstractmethod
    def fetch_messages(self, cursor=None): ...
    @abstractmethod
    def identify_receipts(self, messages): ...
    @abstractmethod
    def parse_receipt(self, message): ...
    @abstractmethod
    def synchronize(self): ...
